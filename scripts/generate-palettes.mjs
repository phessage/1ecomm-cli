/**
 * Derive src/lib/palettes.ts from dt-ui's own palette CSS.
 *
 * The swatches a developer picks a colour from must BE the colours the
 * storefront renders. Hand-typing 24 hex values guarantees they drift the first
 * time a palette is retuned, so the table is generated from
 * packages/core/src/palettes.css plus Tailwind's theme.css, which is where the
 * accent actually resolves.
 *
 * Tailwind v4 states colours in OKLCH, so this converts to sRGB — the terminal
 * cannot render anything else.
 *
 *   node scripts/generate-palettes.mjs <path-to-dt-ui-checkout>
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dtui = process.argv[2] ?? join(here, '..', '..', 'dt-ui');

const palettesCss = join(dtui, 'packages/core/src/palettes.css');
const themeCss = join(dtui, 'node_modules/tailwindcss/theme.css');
for (const f of [palettesCss, themeCss]) {
  if (!existsSync(f)) {
    console.error(`Missing ${f}\nPass the dt-ui checkout path as the first argument.`);
    process.exit(1);
  }
}

/** OKLCH -> linear sRGB -> gamma-encoded sRGB hex. */
function oklchToHex(L, C, hDeg) {
  const h = (hDeg * Math.PI) / 180;
  const a = C * Math.cos(h);
  const b = C * Math.sin(h);

  const l_ = L + 0.3963377774 * a + 0.2158037573 * b;
  const m_ = L - 0.1055613458 * a - 0.0638541728 * b;
  const s_ = L - 0.0894841775 * a - 1.291485548 * b;

  const l = l_ ** 3;
  const m = m_ ** 3;
  const s = s_ ** 3;

  const lr = +4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s;
  const lg = -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s;
  const lb = -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s;

  const enc = (v) => {
    const x = v <= 0.0031308 ? 12.92 * v : 1.055 * Math.pow(v, 1 / 2.4) - 0.055;
    return Math.max(0, Math.min(255, Math.round(x * 255)));
  };
  return `#${[enc(lr), enc(lg), enc(lb)].map((n) => n.toString(16).padStart(2, '0')).join('')}`;
}

// Tailwind's named colours, e.g. `--color-indigo-600: oklch(51.1% 0.262 276.966);`
const tailwind = new Map();
for (const [, name, L, C, H] of readFileSync(themeCss, 'utf8').matchAll(
  /--color-([a-z]+-\d+):\s*oklch\(([\d.]+)%\s+([\d.]+)\s+([\d.]+)\)/g,
)) {
  tailwind.set(name, oklchToHex(Number(L) / 100, Number(C), Number(H)));
}

// dt-ui's palettes, each selecting one Tailwind colour as its accent.
const css = readFileSync(palettesCss, 'utf8');
const palettes = [];
const seen = new Set();
for (const [, name, body] of css.matchAll(
  /\[data-dt-palette=['"]?([a-z0-9-]+)['"]?\]\s*\{([^}]*)\}/g,
)) {
  if (seen.has(name)) continue;
  const accent = /--color-dt-accent:\s*var\(--color-([a-z]+-\d+)\)/.exec(body);
  if (!accent) continue;
  const hex = tailwind.get(accent[1]);
  if (!hex) {
    console.error(`Palette "${name}" references unknown colour ${accent[1]}`);
    process.exit(1);
  }
  seen.add(name);
  palettes.push({ name, hex });
}

if (palettes.length === 0) {
  console.error('Parsed zero palettes. The CSS shape changed; fix this generator.');
  process.exit(1);
}

const out = `/**
 * dt-ui's palettes, with one representative colour each.
 *
 * GENERATED by scripts/generate-palettes.mjs from dt-ui's palettes.css and
 * Tailwind's theme.css. Do not edit: rerun the generator when dt-ui retunes a
 * palette, so the swatch a developer picks stays the colour they get.
 */

export interface Palette {
  /** Value of the storefront's \`data-dt-palette\` attribute. */
  readonly name: string;
  /** sRGB hex of the palette's accent, for a terminal swatch. */
  readonly hex: string;
}

export const PALETTES: readonly Palette[] = ${JSON.stringify(palettes, null, 2)
  .replace(/"name"/g, 'name')
  .replace(/"hex"/g, 'hex')};

export const DEFAULT_PALETTE = 'indigo';

export function isPalette(name: string): boolean {
  return PALETTES.some((p) => p.name === name);
}

export type Appearance = 'light' | 'dark' | 'system';
export const APPEARANCES: readonly Appearance[] = ['light', 'dark', 'system'];
`;

writeFileSync(join(here, '..', 'src', 'lib', 'palettes.ts'), out);
console.log(`Wrote ${palettes.length} palettes to src/lib/palettes.ts`);
